enum TransitAppearance {
    static func isMinibus(_ leg: JourneyLeg) -> Bool {
        if let kind = leg.route?.serviceKind { return kind == "minibus" }
        let id = leg.route?.gtfsId ?? ""
        let unscoped = id.split(separator: ":", maxSplits: 1).last.map(String.init) ?? id
        return leg.mode == "MINIBUS" || minibusIDs.contains(id) || minibusIDs.contains(unscoped)
    }
    static func name(_ leg: JourneyLeg) -> String {
        if let provider = leg.route?.operatorName, !provider.isEmpty { return provider }
        if isMinibus(leg) { return "Minibus" }
        switch leg.mode {
        case "WALK": return "Walk"
        case "SUBWAY", "RAIL": return "MTR"
        case "BUS", "COACH": return "Bus"
        case "FERRY": return "Ferry"
        case "TRAM": return leg.transportLabel ?? "Tram"
        case "FUNICULAR": return "Peak Tram"
        default: return leg.mode.capitalized
        }
    }
    static func symbol(_ leg: JourneyLeg) -> String {
        if isMinibus(leg) { return "bus.fill" }
        switch leg.mode {
        case "WALK": return "figure.walk"
        case "SUBWAY", "RAIL": return "tram.fill"
        case "BUS", "COACH": return "bus.doubledecker.fill"
        case "FERRY": return "ferry.fill"
        case "TRAM", "FUNICULAR": return "tram.fill"
        default: return "arrow.right"
        }
    }
    private static func railLine(_ leg: JourneyLeg, line: String? = nil) -> MTRLineStyle.Line? {
        guard ["SUBWAY", "RAIL"].contains(leg.mode) else { return nil }
        return MTRLineStyle.line(named: line ?? leg.lineName)
    }

    static func detailName(_ leg: JourneyLeg) -> String {
        if leg.isWalking { return "Walk" }
        if ["SUBWAY", "RAIL"].contains(leg.mode) {
            return MTRLineStyle.fullNames(leg.lineName)
        }
        return JourneyText.plain(leg.lineName)
    }

    static func color(_ leg: JourneyLeg, line: String? = nil) -> Color {
        // Canonical MTR line colours take priority over stale server/saved-route metadata.
        if let rail = railLine(leg, line: line) { return hex(rail.hex)! }
        if let providerColor = hex(leg.route?.displayColor) { return providerColor }
        if isMinibus(leg) { return hex("8FAF83")! }
        switch leg.mode {
        case "WALK": return hex("697060")!
        case "BUS", "COACH": return hex("94621E")!
        case "FERRY": return hex("376FA1")!
        case "SUBWAY", "RAIL": return hex("5D6684")!
        default: return hex("427966")!
        }
    }

    static func badgeBackground(_ leg: JourneyLeg, line: String? = nil) -> Color {
        if railLine(leg, line: line) != nil { return color(leg, line: line) }
        if let supplied = hex(leg.route?.badgeColor) { return supplied }
        if isMinibus(leg) { return hex("E5EFDF")! }
        return color(leg, line: line).opacity(0.10)
    }

    static func badgeText(_ leg: JourneyLeg, line: String? = nil) -> Color {
        if let rail = railLine(leg, line: line) {
            // Keep light blue, lime and orange faithful; use dark lettering for readability.
            return ["5EB6E4", "B5BD00", "FE7F1D", "F550A6"].contains(rail.hex) ? AppTheme.ink : .white
        }
        if let supplied = hex(leg.route?.textColor) { return supplied }
        if isMinibus(leg) { return hex("38552F")! }
        return color(leg, line: line)
    }

    private static func hex(_ value: String?) -> Color? {
        guard let value, value.count == 6, let rgb = UInt32(value, radix: 16) else {
            return nil
        }
        return Color(
            red: Double((rgb >> 16) & 255) / 255,
            green: Double((rgb >> 8) & 255) / 255,
            blue: Double(rgb & 255) / 255
        )
    }

